from models import TaskIntent


def trusted_incident_intent(task_id: str) -> TaskIntent:
    """
    Trusted policy contract for the teaching scenario.

    This is deliberately defined by the application, not generated by the LLM.
    The semantic model may interpret a request, but it cannot expand this contract.
    """
    return TaskIntent(
        task_id=task_id,
        purpose="incident_investigation",
        allowed_resources=frozenset({
            "incident_database",
            "network_logs",
            "endpoint_logs",
            "relevant_documents",
            "internal_incident_report",
        }),
        allowed_actions=frozenset({
            "read",
            "analyze",
            "summarize",
            "create_internal_report",
        }),
        prohibited_actions=frozenset({
            "external_disclosure",
            "unauthorized_data_transfer",
            "delete",
            "modify_security_controls",
        }),
        permitted_destinations=frozenset({"internal_report"}),
        sensitivity="confidential",
    )
